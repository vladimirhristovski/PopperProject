from typing import Protocol

from popper_upgrade.skills.schema import DecisionExample, Skill


class SkillSource(Protocol):
    embedding_model: str

    def retrieve_scored(
        self, query: str, k: int, allowed_ids: set[str] | None = None, min_similarity: float = 0.0
    ) -> list[tuple[Skill, float]]: ...

    def list_skills(self, approved: bool | None = True) -> list[Skill]: ...

    def similar_decisions(self, text: str, k: int = 5) -> list[DecisionExample]: ...


class RunSink(Protocol):
    def create_experiment(self, experiment: dict) -> str: ...

    def completed_runs(self, experiment_id: str) -> set[tuple]: ...

    def create_run(self, config: dict) -> str: ...

    def finish_run(self, run_id: str, result: dict) -> None: ...

    def add_run_skills(self, run_id: str, rows: list[dict]) -> None: ...

    def add_design_reviews(self, run_id: str, reviews: list[dict]) -> None: ...

    def add_skill_decision(self, decision: dict) -> str: ...

    def add_candidate_skill(self, skill: Skill) -> str | None: ...
